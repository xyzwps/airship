/**
 * 参数说明的唯一一份文案。
 *
 * 每条只有两句：`what` 说它干什么，`cost` 说代价是什么（慢多少、体积、什么时候不生效）。
 * 悬浮卡是"离开就收"的那种，读的人没有时间翻页，所以宁可少说也不许说错——
 * 凡是"什么时候不生效"的，都以 command.ts 的 build() 与 checks() 为准，不凭印象写。
 *
 * 键名跟着界面上的那一格走；界面上有两格都叫「音频」（选流那一组与输出那一组），
 * 标题就各自带上括号说清是哪一格，不然读的人不知道在解释谁。
 */

export type DemoName = 'crf' | 'faststart' | 'pixfmt'

export interface HelpEntry {
  /** 卡片标题：界面上这一栏念什么，这里就写什么 */
  title: string
  /** 它干什么 */
  what: string
  /** 代价是什么 */
  cost: string
  /** 靠文字说不清的那几处才配一段小动画 */
  demo?: DemoName
}

