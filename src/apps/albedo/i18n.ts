const ZH_TAGS = new Set(['zh', 'zh-hans', 'zh-cn', 'zh-sg'])

/** locale 串 → 语言档；命中 zh 族或 en 族才说话，其余 null */
export function langFromLocale(tag: string): Lang | null {
  const t = String(tag || '')
    .trim()
    .toLowerCase()
    .replace(/_/g, '-')
  if (!t) return null
  if (ZH_TAGS.has(t) || t.startsWith('zh-hans-') || t.startsWith('zh-cn-') || t.startsWith('zh-sg-')) return 'zh'
  if (t === 'en' || t.startsWith('en-')) return 'en'
  return null
}

/** locale 列表 → 语言档，都不命中默认 en */
export function pickLang(tags: string[] | string): Lang {
  const list = Array.isArray(tags) ? tags : [tags]
  for (const tag of list) {
    const hit = langFromLocale(tag)
    if (hit) return hit
  }
  return 'en'
}

function interpolate(text: string, vars: Record<string, unknown>): string {
  return String(text).replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole
  )
}

/** 取词：本语言缺 → 回落 en → 还缺就念键名本身 */
export function t(lang: Lang, key: string, vars: Record<string, unknown> = {}): string {
  const dict = lang === 'zh' ? DICT_ZH : DICT_EN
  const text = dict[key] ?? DICT_EN[key] ?? key
  return interpolate(text, vars)
}

/** 带数量的取词：先试 key.one / key.other，再回落 key 本身；count 自动注入 */
export function tn(lang: Lang, key: string, count: number, vars: Record<string, unknown> = {}): string {
  const suffix = count === 1 ? '.one' : '.other'
  const dict = lang === 'zh' ? DICT_ZH : DICT_EN
  const text = dict[key + suffix] ?? dict[key] ?? DICT_EN[key + suffix] ?? DICT_EN[key] ?? key
  return interpolate(text, { ...vars, count })
}
